-- minimark: single-byte codepage tables for the RTF reader (T5.1).
-- Maps a high byte (0x80..0xFF) to a Unicode code point.  cp1252 is the
-- \ansi default; MacRoman (\mac) is the vintage payoff — old Mac RTFs
-- are MacRoman.  Bytes < 0x80 are ASCII and handled by the caller.
--
-- Both are simple Int->Maybe Int lookups; a Nothing (only cp1252 has a
-- few unassigned slots) becomes U+FFFD upstream.  Written as guards over
-- a literal case so no Data.Char/Unicode predicate touches the hot loop.
module MiniMark.RtfEncoding(cp1252, macRoman) where

-- Windows-1252.  0xA0..0xFF equal their Unicode code points (Latin-1);
-- only 0x80..0x9F differ, and five of those (0x81 0x8D 0x8F 0x90 0x9D)
-- are unassigned -> Nothing.
cp1252 :: Int -> Maybe Int
cp1252 b = case b of
  0x80 -> Just 0x20AC   -- EURO SIGN
  0x81 -> Nothing
  0x82 -> Just 0x201A   -- SINGLE LOW-9 QUOTATION MARK
  0x83 -> Just 0x0192   -- LATIN SMALL LETTER F WITH HOOK
  0x84 -> Just 0x201E   -- DOUBLE LOW-9 QUOTATION MARK
  0x85 -> Just 0x2026   -- HORIZONTAL ELLIPSIS
  0x86 -> Just 0x2020   -- DAGGER
  0x87 -> Just 0x2021   -- DOUBLE DAGGER
  0x88 -> Just 0x02C6   -- MODIFIER LETTER CIRCUMFLEX ACCENT
  0x89 -> Just 0x2030   -- PER MILLE SIGN
  0x8A -> Just 0x0160   -- LATIN CAPITAL LETTER S WITH CARON
  0x8B -> Just 0x2039   -- SINGLE LEFT-POINTING ANGLE QUOTATION MARK
  0x8C -> Just 0x0152   -- LATIN CAPITAL LIGATURE OE
  0x8D -> Nothing
  0x8E -> Just 0x017D   -- LATIN CAPITAL LETTER Z WITH CARON
  0x8F -> Nothing
  0x90 -> Nothing
  0x91 -> Just 0x2018   -- LEFT SINGLE QUOTATION MARK
  0x92 -> Just 0x2019   -- RIGHT SINGLE QUOTATION MARK
  0x93 -> Just 0x201C   -- LEFT DOUBLE QUOTATION MARK
  0x94 -> Just 0x201D   -- RIGHT DOUBLE QUOTATION MARK
  0x95 -> Just 0x2022   -- BULLET
  0x96 -> Just 0x2013   -- EN DASH
  0x97 -> Just 0x2014   -- EM DASH
  0x98 -> Just 0x02DC   -- SMALL TILDE
  0x99 -> Just 0x2122   -- TRADE MARK SIGN
  0x9A -> Just 0x0161   -- LATIN SMALL LETTER S WITH CARON
  0x9B -> Just 0x203A   -- SINGLE RIGHT-POINTING ANGLE QUOTATION MARK
  0x9C -> Just 0x0153   -- LATIN SMALL LIGATURE OE
  0x9D -> Nothing
  0x9E -> Just 0x017E   -- LATIN SMALL LETTER Z WITH CARON
  0x9F -> Just 0x0178   -- LATIN CAPITAL LETTER Y WITH DIAERESIS
  _    -> Just b        -- 0xA0..0xFF: identity (Latin-1 == Unicode)

